//! Conditional no-fill experiment using the pinned native A2 request methods.
//! Input/output are bounded research artifacts, never exchange messages.
use std::collections::BTreeMap;
use std::fs::{File, OpenOptions};
use std::io::{BufRead, BufReader, Write};
use flate2::{read::MultiGzDecoder, write::GzEncoder, Compression};
use pf_engine::ladder::{LadderWindow, Request, SizeLayering};
use pf_strategy::ladder::LadderConfig;
use pf_strategy::Want;
use serde::{Deserialize, Serialize};
use serde_json::json;

const OFF: [Want; 4] = [(None, 0.); 4];
const LINE: f64 = 0.0492;
const DELTA: f64 = 0.01;
const END: f64 = 60000.;

fn cfg() -> LadderConfig {
    let lines = BTreeMap::from([
        ("90".to_string(), [0.0492, 0.0623, 0.0789, 0.0917]),
        ("95".to_string(), [0.0698, 0.0841, 0.1009, 0.1094])]);
    LadderConfig::from_arm("MICRO", ["G4", "G2", "G6", "G5", "G3", "G1", "PM90", "GS", "LD2", "CAP10", "XNA", "XMIN1", "XV", "RO60", "S240"], "AM:5:25:95", &lines).unwrap()
}

#[derive(Clone, Debug, Deserialize)]
struct Event {
    t: f64, kind: u8, input_index: u64, ordinal: u64,
    raw: [Want; 4], relaxed: [Want; 4], v: [Option<f64>; 2],
    binance: [bool; 2], held: bool, net: f64,
}
#[derive(Deserialize)]
struct Window { run: String, mid: u64, start: f64, events: Vec<Event> }
#[derive(Clone, Debug, Serialize)]
struct Ticket {
    id: u64, lane: usize, tick: i32, size: f64, sent: f64, accepted: f64,
    cancel_sent: Option<f64>, end: Option<f64>, release: Option<f64>,
}
#[derive(Clone, Debug, Serialize)]
struct Action {
    index: usize, input_index: u64, ordinal: u64, lane: usize, start: f64, old_tick: i32,
    status: String, order_id: Option<u64>, deadline: Option<f64>, end: Option<f64>, reason: String,
}
#[derive(Clone, Copy, Debug)]
struct Hold { id: u64, deadline: f64, action: usize }
#[derive(Clone, Copy)]
struct Feedback { t: f64, id: u64, kind: u8 }

struct Sim {
    w: LadderWindow, arm: &'static str, previous: [Want; 4],
    tickets: BTreeMap<u64, Ticket>, feedback: Vec<Feedback>,
    holds: [Option<Hold>; 2], actions: Vec<Action>,
    commands: Vec<serde_json::Value>, retry_times: u64,
}
impl Sim {
    fn new(arm: &'static str, mid: u64) -> Self {
        let mut w = LadderWindow::new(cfg(), mid, 0.).with_size_layering(SizeLayering::IncrementalV1);
        // External factual decisions replace prediction/decision triggers only.
        // Retries subsequently generated by request() are run unmodified.
        w.diagnostic_clear_events();
        Self { w, arm, previous: OFF, tickets: BTreeMap::new(), feedback: vec![],
            holds: [None; 2], actions: vec![], commands: vec![], retry_times: 0 }
    }
    fn reserved(&self, side: usize, t: f64) -> f64 {
        self.tickets.values().filter(|o| o.lane % 2 == side && o.sent <= t && o.release.is_none_or(|end| t < end)).map(|o| o.size).sum()
    }
    fn dispatch(&mut self, out: Vec<Request>) {
        for r in out {
            match r {
                Request::Place { id, lane, tick, size, t, .. } => {
                    let sent = self.reserved(lane as usize % 2, t) + size <= 150. + 1e-9;
                    self.commands.push(json!({"kind":"place", "id":id, "lane":lane, "tick":tick, "size":size, "t":t, "sent":sent}));
                    if !sent { self.w.throttled(id, t); continue; }
                    assert!(self.tickets.insert(id, Ticket { id, lane: lane as usize, tick, size, sent:t, accepted:t+40., cancel_sent:None, end:None, release:None }).is_none());
                    self.feedback.push(Feedback { t:t+40., id, kind:0 });
                },
                Request::Cancel { id, lane, t, .. } => {
                    let sent = self.tickets.contains_key(&id);
                    self.commands.push(json!({"kind":"cancel", "id":id, "lane":lane, "t":t, "sent":sent}));
                    if let Some(o) = self.tickets.get_mut(&id) {
                        assert!(o.end.is_none());
                        let end = if t < o.accepted { (t+22.).max(o.sent+95.) } else { t+22. };
                        o.cancel_sent=Some(t); o.end=Some(end); o.release=Some(end+1000.);
                        self.feedback.push(Feedback { t:end, id, kind:1 });
                    }
                },
            }
        }
    }
    fn close(&mut self, lane:usize, t:f64, reason:&str, cancel:bool) {
        let h=self.holds[lane].take().unwrap();
        let a=&mut self.actions[h.action]; a.end=Some(t); a.reason=reason.into();
        if cancel { let mut out=vec![]; self.w.diagnostic_pull(lane,t,&mut out); self.dispatch(out); }
    }
    fn expire(&mut self,t:f64) {
        for lane in 0..2 { if self.holds[lane].is_some_and(|h|h.deadline<=t) { self.close(lane,t,"deadline",true); } }
    }
    fn next_internal(&self) -> f64 {
        let fb=self.feedback.iter().map(|v|v.t).min_by(f64::total_cmp).unwrap_or(f64::INFINITY);
        let hold=self.holds.iter().flatten().map(|h|h.deadline).min_by(f64::total_cmp).unwrap_or(f64::INFINITY);
        fb.min(hold).min(self.w.next_due().unwrap_or(f64::INFINITY))
    }
    fn internal(&mut self,t:f64,expire:bool) {
        // Old experiment expires before same-clock observations. Actual venue
        // feedback precedes native retries, as documented by LadderWindow.
        if expire { self.expire(t); }
        let mut due:Vec<_>=self.feedback.iter().copied().filter(|f|f.t==t).collect();
        self.feedback.retain(|f|f.t!=t); due.sort_by_key(|f|(f.kind,f.id));
        for f in due {
            if f.kind==0 { self.w.answered(f.id); self.w.accepted(f.id); }
            else { self.w.cancel_done(f.id); }
        }
        if self.w.next_due()==Some(t) {
            let mut out=vec![]; self.w.run_retries(t,&mut out); self.retry_times+=1; self.dispatch(out);
            assert!(self.w.next_due().is_none_or(|n|n>t),"non-retry event escaped the conditional harness");
        }
    }
    fn before(&mut self,t:f64) {
        loop { let n=self.next_internal(); if n>=t {break;} self.internal(n,true); }
        self.internal(t,self.arm!="update_first50");
    }
    fn eligible(&self,e:&Event,l:usize,id:u64,opening:bool) -> Option<&'static str> {
        let o=self.w.order(id).unwrap();
        if o.cancelled || o.refused || !o.live || o.open()<=0. {return Some("order_unavailable");}
        if e.held {return Some("held");}
        if e.binance[l] {return Some("binance");}
        let Some(v)=e.v[l].filter(|v|v.is_finite()) else {return Some("missing_score")};
        if v<=LINE-DELTA {return Some("lower_line");}
        if opening && v>LINE {return Some("not_soft_exit");}
        if e.relaxed[l].0!=Some(o.tick) || e.relaxed[l].1+1e-9<o.open() {return Some("native_price_size_guard");}
        if e.raw[l+2].0==Some(o.tick) && e.raw[l+2].1>0. {return Some("duplicate_rung");}
        None
    }
    fn observe(&mut self,e:&Event) {
        for l in 0..2 { if let Some(h)=self.holds[l] {
            if let Some(reason)=self.eligible(e,l,h.id,false) {self.close(l,e.t,reason,true);}
        } }
    }
    fn decision(&mut self,e:&Event,index:usize) {
        for l in 0..2 {if let Some(h)=self.holds[l] {
            if let Some(pt)=e.raw[l].0 {
                let reason=if self.w.order(h.id).unwrap().tick==pt {"same_price_reopen"} else {"other_price_reopen"};
                self.close(l,e.t,reason,false);
            }
        }}
        self.observe(e);
        for l in 0..2 {
            let Some(old_tick)=self.previous[l].0 else {continue};
            if e.raw[l].0.is_some() {continue;}
            let ai=self.actions.len();
            let mut a=Action{index,input_index:e.input_index,ordinal:e.ordinal,lane:l,start:e.t,old_tick,
                status:"reference_cancel".into(),order_id:None,deadline:None,end:Some(e.t),reason:"not_retained".into()};
            if self.arm!="reference" {
                let candidates:Vec<_>=[l,l+4].into_iter().filter_map(|m|self.w.diagnostic_current(m))
                    .filter(|&id|{let o=self.w.order(id).unwrap(); self.w.known(o.lane)==Some(id) && o.live && !o.cancelled && !o.refused && o.tick==old_tick && o.size<=5. && o.open()>0. && o.open()<=5.}).collect();
                if candidates.len()!=1 {a.status="no_accepted_small_front".into();}
                else if let Some(reason)=self.eligible(e,l,candidates[0],true) {a.status=reason.into();}
                else {
                    let id=candidates[0];let deadline=e.t+if self.arm=="all100"{100.}else{50.};
                    a.status="retained".into(); a.order_id=Some(id);a.deadline=Some(deadline);a.end=None;a.reason=String::new();
                    assert!(self.holds[l].is_none());self.holds[l]=Some(Hold{id,deadline,action:ai});
                }
            }
            self.actions.push(a);
        }
        let mut want=e.raw;
        for l in 0..2 {if let Some(h)=self.holds[l] {let o=self.w.order(h.id).unwrap();want[l]=(Some(o.tick),o.size);}}
        let mut out=vec![];self.w.diagnostic_wants(e.t,&want,&mut out);
        for r in &out {if let Request::Place{lane,..}=r {assert!(e.raw[*lane as usize%4].0.is_some(),"new order while guard off");}}
        self.dispatch(out);self.previous=e.raw;
    }
    fn run(mut self,events:&[Event]) -> serde_json::Value {
        let mut i=0;
        while i<events.len() {
            let t=events[i].t;self.before(t);
            while i<events.len() && events[i].t==t {
                let e=&events[i];
                if e.kind==0 {self.decision(e,i);} else if e.kind==1 {self.observe(e);}
                // Factual inventory notices affect only exposure measurement.
                i+=1;
            }
            if self.arm=="update_first50" {self.expire(t);}
        }
        self.before(END);
        for l in 0..2 {if self.holds[l].is_some(){self.close(l,END,"window_censored",false);}}
        json!({"arm":self.arm,"orders":self.tickets.values().collect::<Vec<_>>(),"actions":self.actions,
            "commands":self.commands,"counts":self.w.counts(),"retry_times":self.retry_times})
    }
}

fn validate(events:&[Event]) -> Result<(),String> {
    if events.is_empty() {return Err("empty window".into());}
    let mut last=None;
    for e in events {
        let key=(e.t,e.input_index,e.kind,e.ordinal);
        if !(e.t.is_finite() && e.t>=0. && e.t<END && e.net.is_finite() && e.kind<=2) {return Err("bad timestamp/state".into());}
        if last.is_some_and(|k|key<k) {return Err("event order regressed".into());} last=Some(key);
        for &(tick,size) in e.raw.iter().chain(e.relaxed.iter()) {
            if !size.is_finite() || size<0. || tick.is_some_and(|p|!(1..100).contains(&p)) || (tick.is_none() && size!=0.) {return Err("invalid quote".into());}
        }
    }
    Ok(())
}

fn main() {
    let args:Vec<_>=std::env::args().collect();assert_eq!(args.len(),3);
    let source=BufReader::new(MultiGzDecoder::new(File::open(&args[1]).unwrap()));
    let mut dest=GzEncoder::new(OpenOptions::new().write(true).create_new(true).open(&args[2]).unwrap(),Compression::fast());
    let mut count=0;
    for line in source.lines() {
        let w:Window=serde_json::from_str(&line.unwrap()).unwrap();validate(&w.events).unwrap();
        let arms:Vec<_>=["reference","all100","update_first50"].into_iter().map(|arm|Sim::new(arm,w.mid).run(&w.events)).collect();
        serde_json::to_writer(&mut dest,&json!({"run":w.run,"mid":w.mid,"start":w.start,"events":w.events.len(),"arms":arms})).unwrap();dest.write_all(b"\n").unwrap();
        count+=1;if count%20==0{eprintln!("windows={count}");}
    }
    dest.finish().unwrap();assert_eq!(count,220);
}

#[cfg(test)]
mod tests {
    use super::*;
    fn event(t:f64,on:bool) -> Event {
        let mut raw=OFF;if on{raw[0]=(Some(50),5.);}
        let mut relaxed=OFF;relaxed[0]=(Some(50),5.);
        Event{t,kind:0,input_index:t as u64,ordinal:0,raw,relaxed,v:[Some(if on{0.06}else{0.045});2],binance:[false;2],held:false,net:0.}
    }
    fn wants(w:&mut LadderWindow,t:f64,z:f64)->Vec<Request>{let mut q=OFF;q[0]=(Some(50),z);let mut out=vec![];w.diagnostic_wants(t,&q,&mut out);out}
    fn place_id(v:&[Request])->u64{match v[0]{Request::Place{id,..}=>id,_=>panic!("expected place")}}
    #[test] fn whole_first_and_incremental_keep() {
        let mut w=Sim::new("reference",7).w;let p=wants(&mut w,0.,25.);assert_eq!(p.len(),1);assert_eq!(w.order(place_id(&p)).unwrap().size,25.);
        let mut w=Sim::new("reference",7).w;let p=wants(&mut w,0.,5.);let id=place_id(&p);w.answered(id);w.accepted(id);
        let p=wants(&mut w,50.,25.);assert_eq!(p.len(),1);assert!(matches!(p[0],Request::Place{lane:4,size:20.,..}));assert!(!w.order(id).unwrap().cancelled);
    }
    #[test] fn pair_partial_fill_not_replenished_and_front_rotates() {
        let mut w=Sim::new("reference",7).w;let p=wants(&mut w,0.,5.);let id=place_id(&p);w.answered(id);w.accepted(id);
        let p=wants(&mut w,50.,25.);let other=place_id(&p);w.answered(other);w.accepted(other);
        w.filled(id,2.,60.);assert!(wants(&mut w,70.,25.).is_empty());
        w.filled(id,3.,80.);assert!(wants(&mut w,90.,25.).is_empty());assert_eq!(w.known(4),Some(other));
        let p=wants(&mut w,100.,30.);assert_eq!(p.len(),1);assert!(matches!(p[0],Request::Place{lane:0,size:10.,..}));
    }
    #[test] fn rejected_resets_but_local_refusal_backs_off() {
        let mut w=Sim::new("reference",7).w;let p=wants(&mut w,0.,5.);w.throttled(place_id(&p),0.);
        assert!(wants(&mut w,10.,5.).is_empty());assert_eq!(w.next_due(),Some(250.));
        let mut p=vec![];w.run_retries(250.,&mut p);assert_eq!(p.len(),1);w.throttled(place_id(&p),250.);assert_eq!(w.next_due(),Some(750.));
        let mut w=Sim::new("reference",7).w;let p=wants(&mut w,0.,5.);w.rejected(place_id(&p));assert_eq!(wants(&mut w,10.,5.).len(),1);
    }
    #[test] fn equal_clock_bridge_and_late_reopen_refusal() {
        for (reopen,reason) in [(150.,"same_price_reopen"),(151.,"deadline")] {
            let s=Sim::new("update_first50",7).run(&[event(0.,true),event(100.,false),event(reopen,true)]);
            assert_eq!(s["actions"][0]["reason"],reason);assert_eq!(s["actions"][0]["end"],150.);
        }
    }
    #[test] fn lower_line_probe_cancels_without_new_quotes() {
        let mut probe=event(125.,false);probe.kind=1;probe.v=[Some(0.02);2];
        let s=Sim::new("update_first50",7).run(&[event(0.,true),event(100.,false),probe]);
        assert_eq!(s["actions"][0]["reason"],"lower_line");assert_eq!(s["actions"][0]["end"],125.);
        assert_eq!(s["counts"]["places"],1);
    }
    #[test] fn cap_includes_cancel_reservation_and_release_boundary() {
        let mut s=Sim::new("reference",7);s.tickets.insert(9,Ticket{id:9,lane:0,tick:50,size:150.,sent:0.,accepted:40.,cancel_sent:Some(50.),end:Some(72.),release:Some(1072.)});
        assert_eq!(s.reserved(0,1071.),150.);assert_eq!(s.reserved(1,1071.),0.);assert_eq!(s.reserved(0,1072.),0.);
        let p=wants(&mut s.w,100.,5.);s.dispatch(p);assert_eq!(s.w.counts().throttled_locally,1);assert_eq!(s.w.next_due(),Some(350.));
    }
    #[test] fn input_positive_and_bad_timestamp_refusal() {
        assert!(validate(&[event(0.,true),event(50.,false)]).is_ok());
        assert!(validate(&[event(50.,true),event(0.,false)]).is_err());
        assert!(validate(&[event(END,true)]).is_err());
    }
}
