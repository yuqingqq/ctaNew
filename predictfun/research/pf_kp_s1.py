        return dict(thinning=np.expm1(own_now) <= 0.8 * np.expm1(own_250), side=sg * imb1 <= -1.0 / 3.0,
                    burst=(act_rel >= np.log(2.0)) & (sg * flow < 0), bshift=sg * d_bnimb <= -0.3, guard=np.asarray(v) <= -0.10)


