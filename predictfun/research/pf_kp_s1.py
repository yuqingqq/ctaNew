def delta(t0, tb, vb, tf_, vf, H):
    """Delta = Q_keep - Q_pull per markout column, c per share of our order, for a decision at t0. tb / vb: the base path's fill
    times and shares x value; tf_ / vf: the fork's. Fills inside the cancel latency (t0, t0 + 22 ms] happen on both paths."""
    lo = t0 + (0.0 if MUT_LAT_IN else L_CANCEL); up = t0 + H
    qk = vb[(tb > lo) & (tb <= up)].sum(0) if len(tb) else np.zeros(len(HM))
    qp = vf[tf_ <= up].sum(0) if len(tf_) else np.zeros(len(HM))
    return (qk - qp) / SIZE, qk / SIZE, qp / SIZE


def kp_case(fr, tr, k, H=2000.0, qrule='M'):
    """A synthetic bid-side case: the base path, the pull fork from step k and the label at k, with the value of a fill = -1 per
    share through our price and +1 at it."""
