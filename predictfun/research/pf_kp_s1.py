            if REST_STATE is not None:                    # keep-or-pull S1: our order's age if it rests at this step (before the decision)
                REST_STATE.append((t - cur['ta']) if (cur is not None and not cur['ref'] and cur['ta'] <= t and cur['rem'] > 1e-12) else -1.0)
