def run_fork(k, side, tf, opp, P5, S5, cache, tg, vkl, stl, best, bopp, tt, ptl, shl, q, t_end, capture=False):
    """S1 pull path from step k: no order of ours after t_k; a new one rests (never pulled) from the first step at or after
    t_k + 250 ms, to t_end. Returns (fills, orders, rest states of steps k2..kend-1, k2); fills carry the trade index as sim2's."""
