def kp_selftest():
    """K2 fork cases with known answers and K3 planted errors (each must break a K2 case); returns the failures."""
    bad = []
    B50 = (-100, [(50, 100)], 52)
    cases = {
        # a pull at 100 ms before a sweep at 200: the base order is swept, the pull path re-enters at 350 (live 390) after it
        'FK1': (([B50], [(200, 49, 120)], 2), dict(base=[(200.0, 50, 5.0, True)], fork=[], delta=-1.0,
                                                  rs8=[-1.0, 10.0, 60.0, 110.0, -1.0, -1.0, -1.0, 10.0])),
        # the base order reaches the front (a 100-sh sell uses up the queue) and gets a benign 5-sh fill at 500; the re-entered order
        # joins behind 50 sh and is not reached by 5 + 25 sh: pulling loses the fill
        'FK2': (([B50, (310, [(50, 50)], 52)], [(300, 50, 100), (500, 50, 5), (600, 50, 25)], 2),
                dict(base=[(500.0, 50, 5.0, False)], fork=[], delta=1.0, a0=[50.0])),
        # a sweep at 110, inside the 22 ms cancel latency of a decision at 100: on both paths, so not in the label
        'FK4': (([B50], [(110, 49, 120)], 2), dict(base=[(110.0, 50, 5.0, True)], fork=[], delta=0.0)),
    }
    got = {}
    for name, (args, want) in cases.items():
        g = kp_case(*args); got[name] = g
        for key, w in want.items():
            gv = g['rs'][:8] if key == 'rs8' else g[key]
            if gv != w:
                bad.append((name, key, gv))
    global MUT_FORK_NOCOOL, MUT_FORK_FRONT, MUT_LAT_IN
    for mut, case in (('MUT_FORK_NOCOOL', 'FK1'), ('MUT_FORK_FRONT', 'FK2'), ('MUT_LAT_IN', 'FK4')):
        globals()[mut] = 1
        try:
            g = kp_case(*cases[case][0])
        finally:
            globals()[mut] = 0
        if g['delta'] == cases[case][1]['delta'] and g['fork'] == cases[case][1]['fork']:
            bad.append((mut, f'passed {case}'))
    if MUT_FORK_NOCOOL or MUT_FORK_FRONT or MUT_LAT_IN or REST_STATE is not None:
        bad.append(('restore', 'a planted switch or the capture was left on'))
    return bad


