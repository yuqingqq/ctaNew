def order_steps(W, r, shf, src, tkv, tkp, st):
    """Decision states (every EVERY_ALIGN-th step) of every client-known resting order and its fills in (t + 22, t + H] for each H:
    shares q, value v (1 s markout, cents x shares), vo (fills on orders >= 100 ms old), WS-anchored value and THROUGH shares at 1 s."""
    cols = {c: [] for c, _ in OS_COLS}; vals = {c: [] for c in OS_VALS}
    m = int(W[0]['m'])
    for s in (0, 1):
        w = W[s]; tf, mff = w['tf_mff']; sg = float(w['sg']); anc = np.asarray(w['anc'], float); tt = (np.asarray(w['anc'], float) - shf)
        tg = np.asarray(w['tg'], float); best = np.asarray(w['best'], 'int64')
        for d in range(NR):
            orders = [o for o in r['order_states'][(s, d)] if not o['ref']]
            fl = {id(o): [] for o in orders}
            for f in r['fills'][(s, d)]:
                i, pt, qq, thr, age = int(f[0]), int(f[1]), float(f[2]), bool(f[3]), float(f[4]); t = float(tt[i])
                cand = [o for o in orders if o['pt'] == pt and o['ta'] <= t < o['tr'] and (MUT_MATCH_NO_TFILL or t <= o['tfill'])]
                if len(cand) != 1:
                    st['unmatched_fills'] += 1; continue
                j1 = max(int(np.searchsorted(tf, anc[i] + 1000.0, side='right')) - 1, 0)
                v1 = sg * (float(mff[j1]) - pt)
                ty = fill_type(s, pt, thr, tkp[s].get(int(tkv[s][i]), [pt]))
                fl[id(cand[0])].append((t, qq, v1, float(age >= YOUNG_MS), float(bool(src[s][i])), float(ty == 'THROUGH')))
                st['fills'] += 1
            for o in orders:
                F = sorted(fl[id(o)]); cum = 0.0; tfull = INF
                if F:
                    st['matched_orders'] += 1
                for x in F:
                    cum += x[1]
                    if cum >= SIZE - 1e-9:
                        tfull = x[0] + CL.L_NOTE; break
                t_end = min(o['tc'], tfull)
                k0 = int(np.searchsorted(tg, o['ta'], side='left')); k1 = int(np.searchsorted(tg, t_end, side='left'))
                ks = np.arange(k0, k1); ks = ks[ks % EVERY_ALIGN == 0]
                if len(ks):
                    bk = best[ks]; ks = ks[bk >= 0]; bk = bk[bk >= 0]
                if not len(ks):
                    continue
                ft = [x[0] for x in F]; q = [x[1] for x in F]; qv = [x[1] * x[2] for x in F]; qvo = [x[1] * x[2] * x[3] for x in F]
                for h in HS:
                    a, b_, c_ = horizon_sums(ft, [q, qv, qvo], tg[ks], h=h)
                    vals[f'q{h}'].append(a.astype(np.float32)); vals[f'v{h}'].append(b_.astype(np.float32)); vals[f'vo{h}'].append(c_.astype(np.float32))
                a, b_ = horizon_sums(ft, [[x[1] * x[2] * x[4] for x in F], [x[1] * x[5] for x in F]], tg[ks], h=HS[-1])
                vals['vws1000'].append(a.astype(np.float32)); vals['qthr1000'].append(b_.astype(np.float32))
                n_ = len(ks); st['order_steps'] += n_
