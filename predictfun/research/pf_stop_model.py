def label_brute(tf, b0, valid, side, jk, t, lc=None, h=None):
    """Independent recomputation of (D0, D1_h, quiet) by an explicit frame walk (control (c); not used to build labels)."""
    lc = L_C if lc is None else lc; h = H_MS if h is None else h
    ref = int(b0[jk]); n = len(tf)

    def adv(p):
        return (ref - int(p)) if side == 0 else (int(p) - ref)
    D0 = 0; last = ref; i = jk + 1
    while i < n and tf[i] <= t + lc:
        if valid[i]:
            D0 = max(D0, adv(b0[i])); last = b0[i]
        i += 1
    D1 = max(0, adv(last)); quiet = True
    while i < n and tf[i] <= t + h:
        if valid[i]:
            D1 = max(D1, adv(b0[i])); quiet = False
        i += 1
    return float(D0), float(D1), bool(quiet)


def horizon_gap(tf, tfl, jk, t, own_empty):
    """Label-side statuses: the largest gap (ms) between consecutive frames of ANY kind over the 1 s label window (the last frame stamped
    <= t + 22 ms, the frames stamped in (t + 22, t + 1000] and the window's end), and whether a frame there has our side empty."""
    j0 = bisect.bisect_right(tfl, t + L_C); j1 = bisect.bisect_right(tfl, t + H_MS)
    jl = max(j0 - 1, jk)
    seq = np.concatenate([[float(tf[jl])], np.asarray(tf[j0:j1], float), [t + H_MS]])
    return float(np.diff(seq).max()), bool(np.asarray(own_empty[j0:j1]).any())


