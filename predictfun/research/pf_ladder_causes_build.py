"""Generate pf_step4_ladder_causes.py = the FROZEN ladder engine of pm_ladder_v1 plus the same 21 read-only hooks as the lockstep trace
(pf_ladder_trace_build.PATCHES), wired to pf_ladder_causes.py (order-change causes) instead of pf_ladder_tracer.py. The frozen file is never
edited; refuses unless the source hash matches and every anchor occurs exactly once. Outputs must stay byte-identical to round i
(checked by pf_causes_report.py).
Usage: python3 -m predictfun.research.pf_ladder_causes_build
"""
import hashlib, os, sys
from . import pf_ladder_trace_build as TB

DST = os.path.join(TB.HERE, 'pf_step4_ladder_causes.py')
IMP = ('from . import pf_io as io\n', 'from . import pf_io as io\nfrom . import pf_ladder_tracer as _TRM\n_TR = _TRM.Tracer()\n')


def main():
    src = open(TB.SRC, 'rb').read()
    h = hashlib.sha256(src).hexdigest()
    if h != TB.FROZEN:
        sys.exit(f'REFUSED: {TB.SRC} sha256 {h} is not the frozen engine {TB.FROZEN}')
    if TB.PATCHES[0] != IMP:
        sys.exit('REFUSED: the trace builder import patch changed')
    patches = [('from . import pf_io as io\n', 'from . import pf_io as io\nfrom . import pf_ladder_causes as _TRM\n_TR = _TRM.Tracer()\n')] + TB.PATCHES[1:]
    s = src.decode()
    for a, b in patches:
        n = s.count(a)
        if n != 1:
            sys.exit(f'REFUSED: anchor occurs {n} times: {a[:80]!r}')
        s = s.replace(a, b)
    s += '_TR.close()\n'
    out = (f'# GENERATED by pf_ladder_causes_build.py from pf_step4_ladder.py sha256 {TB.FROZEN} (frozen engine of pm_ladder_v1)\n'
           f'# plus the lockstep trace hooks ({len(patches)} anchored insertions) wired to pf_ladder_causes. Do not edit; regenerate.\n') + s
    open(DST, 'w').write(out)
    print(f'wrote {DST} sha256 {hashlib.sha256(out.encode()).hexdigest()} ({len(patches)} insertions)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
